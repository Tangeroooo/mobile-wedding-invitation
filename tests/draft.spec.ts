test('short screens, viewport bounds and reduced motion', async ({ page }) => {
  await page.setViewportSize({width:320,height:568})
  await page.emulateMedia({ reducedMotion:'reduce' })
  await page.goto('draft/')
  await expect(page.locator('.draft-letter-svg')).toBeVisible()
  await page.getByRole('button', { name:'문구 · 배경 편집' }).click()
  await page.getByLabel('가로 위치', {exact:true}).fill('0')
  await page.getByLabel('세로 위치', {exact:true}).fill('0')
  await page.getByRole('button', { name:'편집 도구 닫기' }).click()
  const block = (await page.locator('.draft-selection').boundingBox())!
  const stage = (await page.locator('.draft-stage').boundingBox())!
  expect(block.x).toBeGreaterThanOrEqual(stage.x - 1)
  expect(block.y).toBeGreaterThanOrEqual(stage.y - 1)
  await page.getByRole('button', { name:'전체 재생' }).click()
  await expect(page.locator('.draft-write').first()).toHaveCSS('animation-name','none')
  await page.getByRole('button', { name:'건너뛰기' }).click()
  await expect(page.locator('.draft-intro-layer')).toHaveCount(0)
  await page.getByRole('button', { name:'편집으로' }).click()
  expect(await page.evaluate(() => document.body.style.overflow)).not.toBe('hidden')
})
